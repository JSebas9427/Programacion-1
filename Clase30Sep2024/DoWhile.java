public class DoWhile {
    public static void main(String[] args) {
        int i = 1;
        String cad = "Programacion 1";
        do {
            System.out.println(cad);
            i++;
        } while (i > 5);


        for (int j = 0; j < 5; j++) {
          System.out.println(cad);  
        }
    }
}
